/**
 * Parse draft status from string, with fallback to generating.
 */
export function parseDraftStatus(
  value: string | undefined | null
): DraftStatus {
  if (!value) return "generating";
  const normalized = value.toLowerCase().trim();
  return VALID_DRAFT_STATUSES.includes(normalized as DraftStatus)
    ? (normalized as DraftStatus)
    : "generating";
}

/**
 * Normalize timestamp to milliseconds.
 * Handles both seconds and milliseconds from the agent.
 */
export function normalizeDraftTimestamp(
  ts: number | undefined | null
): number {
  if (ts === undefined || ts === null || ts === 0) {
    return Date.now();
  }
  // If timestamp is less than 1e12, it's in seconds
  return ts < 1e12 ? ts * 1000 : ts;
}

/**
 * Normalize confidence from integer (0-100) to float (0.0-1.0).
 */
export function normalizeDraftConfidence(
  value: number | undefined | null
): number {
  if (value === undefined || value === null) {
    return DEFAULT_DRAFT_CONFIDENCE;
  }
  // If value is > 1, assume it's a percentage
  if (value > 1) {
    return value / 100;
  }
  return value;
}

/**
 * Format timestamp for display (HH:MM format).
 */
export function formatDraftTime(timestamp: number): string {
  return new Date(timestamp).toLocaleTimeString([], {
    hour: "2-digit",
    minute: "2-digit",
  });
}

/**
 * Check if a draft can be edited.
 */
export function isDraftEditable(status: DraftStatus): boolean {
  return status === "ready" || status === "edited";
}

/**
 * Check if a draft can be sent.
 */
export function isDraftSendable(status: DraftStatus): boolean {
  return status === "ready" || status === "edited";
}

/**
 * Get initials from a name for avatar display.
 */
export function getRecipientInitials(name: string): string {
  return name
    .split(" ")
    .map((part) => part[0])
    .join("")
    .toUpperCase()
    .slice(0, 2);
}

/**
 * Format recipients list for display.
 */
export function formatRecipients(recipients: EmailRecipient[]): string {
  if (recipients.length === 0) return "No recipients";
  if (recipients.length === 1) {
    return recipients[0].email || recipients[0].name;
  }
  return `${recipients[0].email || recipients[0].name} +${recipients.length - 1}`;
}

/**
 * Truncate text to a maximum length with ellipsis.
 */
export function truncateText(text: string, maxLength: number): string {
  if (text.length <= maxLength) return text;
  return text.slice(0, maxLength - 3) + "...";
}

/**
 * Parse email recipients from agent data.
 */
export function parseEmailRecipients(
  data: unknown
): EmailRecipient[] {
  if (!Array.isArray(data)) return [];

  return data
    .filter((item): item is Record<string, unknown> =>
      item !== null && typeof item === "object"
    )
    .map((item) => ({
      email: typeof item.email === "string" ? item.email : null,
      name: typeof item.name === "string" ? item.name : "Unknown",
      source: (["inferred", "explicit", "participant"].includes(item.source as string)
        ? item.source
        : "inferred") as EmailRecipient["source"],
    }));
}

/**
 * Parse meeting context from agent data.
 */
export function parseMeetingContext(
  data: unknown
): MeetingContext {
  if (!data || typeof data !== "object") {
    return DEFAULT_MEETING_CONTEXT;
  }

  const ctx = data as Record<string, unknown>;

  return {
    meetingTitle: typeof ctx.meetingTitle === "string" ? ctx.meetingTitle : null,
    meetingDate: typeof ctx.meetingDate === "string" ? ctx.meetingDate : null,
    participants: Array.isArray(ctx.participants)
      ? ctx.participants.filter((p): p is string => typeof p === "string")
      : [],
    agendaTopics: Array.isArray(ctx.agendaTopics)
      ? ctx.agendaTopics.filter((t): t is string => typeof t === "string")
      : [],
    roomId: typeof ctx.roomId === "string" ? ctx.roomId : null,
  };
}

/**
 * Validate that a string is non-empty after trimming.
 */
export function isNonEmptyDraftString(value: unknown): value is string {
  return typeof value === "string" && value.trim().length > 0;
}
