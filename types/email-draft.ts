/**
 * Email Draft Types for Luframe Frontend
 *
 * These types match the backend schemas/email_draft.py and are used
 * for real-time email draft generation and display.
 *
 * Email drafts are generated when ActionClassifier identifies email-type actions
 * and EmailDraftGenerator creates AI-generated drafts for user review.
 */

// ============================================================================
// Constants
// ============================================================================

/**
 * Maximum number of email drafts to keep in memory.
 */
export const MAX_DRAFTS = 50;

/**
 * Confidence threshold for displaying low-confidence indicators.
 */
export const DRAFT_CONFIDENCE_THRESHOLD = 0.6;

/**
 * Default confidence value when not provided.
 */
export const DEFAULT_DRAFT_CONFIDENCE = 0.8;

// ============================================================================
// Types
// ============================================================================

/**
 * Status of an email draft in its lifecycle.
 * Matches DraftStatus enum from backend.
 */
export type DraftStatus =
  | "generating" // Draft is being generated by LLM
  | "ready" // Draft is ready for user review
  | "edited" // User has edited the draft
  | "sent" // Email has been sent
  | "rejected" // User rejected the draft
  | "failed"; // Generation failed

/**
 * All valid draft statuses for validation.
 */
export const VALID_DRAFT_STATUSES: DraftStatus[] = [
  "generating",
  "ready",
  "edited",
  "sent",
  "rejected",
  "failed",
];

/**
 * Email recipient with optional metadata.
 * Matches EmailRecipient from backend.
 */
export interface EmailRecipient {
  /** Email address if known (from participant list) */
  email: string | null;
  /** Name or role of the recipient */
  name: string;
  /** How recipient was determined: 'inferred', 'explicit', 'participant' */
  source: "inferred" | "explicit" | "participant";
}

/**
 * Meeting context information for email generation.
 * Provides relevant meeting details for contextually appropriate drafts.
 */
export interface MeetingContext {
  /** Title of the meeting */
  meetingTitle: string | null;
  /** Date of the meeting (ISO format or human readable) */
  meetingDate: string | null;
  /** List of participant names in the meeting */
  participants: string[];
  /** Agenda topics being discussed */
  agendaTopics: string[];
  /** Room identifier for meeting links */
  roomId: string | null;
}

/**
 * Default meeting context values.
 */
export const DEFAULT_MEETING_CONTEXT: MeetingContext = {
  meetingTitle: null,
  meetingDate: null,
  participants: [],
  agendaTopics: [],
  roomId: null,
};

/**
 * An AI-generated email draft from a meeting action item.
 * Matches EmailDraft from backend (camelCase).
 */
export interface EmailDraft {
  /** Unique draft identifier */
  id: string;

  // Link to source action and meeting
  /** ID of the ClassifiedAction that triggered this draft */
  actionId: string;
  /** ID of the original action_item insight */
  originalInsightId: string;
  /** ID of the meeting this draft belongs to (for audit logging) */
  meetingId: string;
  /** Room ID for quick access */
  roomId: string;

  // Email content
  /** Suggested email recipients */
  suggestedTo: EmailRecipient[];
  /** Email subject line */
  subject: string;
  /** Email body content */
  body: string;

  // Context that generated this draft
  /** Meeting context used for generation */
  meetingContext: MeetingContext;
  /** Transcript excerpt used for generation */
  transcriptContext: string | null;

  // Source action data (copied for convenience)
  /** Original action item content */
  actionContent: string;
  /** Type of email action (email_followup, email_share, email_schedule) */
  actionType: string;
  /** Name of person who mentioned the action */
  speakerName: string | null;

  // Draft metadata
  /** Current status of the draft */
  status: DraftStatus;
  /** Confidence in draft quality (0.0-1.0) */
  generationConfidence: number;

  // Timestamps
  /** When the draft was generated (ms) */
  generatedAt: number;

  // Error tracking (for failed status)
  /** Error message if generation failed */
  errorMessage: string | null;
}

/**
 * User edits to an email draft before sending.
 */
export interface EmailDraftEdits {
  /** Edited recipients */
  to?: string[];
  /** Edited CC recipients */
  cc?: string[];
  /** Edited subject line */
  subject?: string;
  /** Edited body content */
  body?: string;
}

/**
 * Full email data ready for sending (draft + edits).
 */
export interface EmailToSend {
  /** Draft ID for reference */
  draftId: string;
  /** Meeting ID for audit trail */
  meetingId?: string;
  /** Final recipients (email addresses) */
  to: string[];
  /** CC recipients */
  cc?: string[];
  /** Final subject line */
  subject: string;
  /** Final body content */
  body: string;
}

